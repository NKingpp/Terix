#!/usr/bin/env bash
#
# check-claims.sh —— 列出所有「注释声称有保障」的位置，供人工逐条核对。
#
# # 为什么只列出、不判定失败
#
# 「注释说已测试」可能指的不是 Go 测试 —— 比如「人工验证过」「已在浏览器里点过」。
# 所以脚本不做判定，只把清单打出来，由人判断每一条是否成立。
#
# # 为什么需要这个脚本
#
# 实测（2026-10-29）：`providerMeta` 的字段注释写着「两份都从同一份定义派生，
# 有测试保证一致」，而全仓 grep 找不到那个测试 ——
# 意味着「Fields[].Required 与 RequiredFields 不一致」这个缺陷可以长期存在。
#
# 「注释声称有保障而保障不存在」的危害高于「注释说错因果」：
# 后者让人跳过检查（但可能自己发现错），前者让人**完全不去检查**（因为以为已有防护）。
#
# 规则：注释里写「有 X 保证 / 已测试 / 有单测覆盖」时，必须附具体位置
# （文件名:行号 或 测试函数名）。指不出来的，那句话不是说明，是愿望。
#
# 用法：
#   ./scripts/check-claims.sh            # 列出全部
#   ./scripts/check-claims.sh --strict   # 排除「关于这条规则的说明文字」后的真实断言

set -uo pipefail

cd "$(dirname "$0")/.." || exit 1

PATTERN='有测试保证|已测试|有单测覆盖|test-covered|有断言保证'

if [[ "${1:-}" == "--strict" ]]; then
  # 排除「说明历史错误」的引用 —— 那类文字会提到这些关键词，但它是在描述
  # 「原先的写法为什么错」，不是实际断言。
  #
  # ⚠️ 这个排除是启发式的：它依赖说明文字里含「原先」或「这条注释」。
  #    所以 --strict 的输出更短，但仍需人工过一遍。
  echo "=== 声称有保障的注释（已排除说明文字）==="
  grep -rnE "$PATTERN" --include="*.go" . 2>/dev/null \
    | grep -v "原先写\|原先声称\|这条注释\|说明文字" \
    | sort
else
  echo "=== 声称有保障的注释（全部，含说明文字）==="
  grep -rnE "$PATTERN" --include="*.go" . 2>/dev/null | sort
fi

echo
echo "---"
echo "每条命中都是一个「待验证的断言」。请逐条核对："
echo "  ① 那句话指的测试真的存在吗？（grep 那个函数名）"
echo "  ② 如果不存在 —— 是补测试，还是把注释改成「未覆盖」？"
echo "  ③ 如果存在 —— 注释里写清是哪个测试了吗？（否则下一个人仍无法验证）"
